// Helper functions for easy consumption across the app
export function getCountryByCode(code: string): CountryProfile | undefined {
  const upper = code.toUpperCase();
  return COUNTRIES_195.find((c) => c.code === upper);
}

export function searchCountries(query: string): CountryProfile[] {
  const q = query.toLowerCase().trim();
  if (!q) return COUNTRIES_195;
  return COUNTRIES_195.filter(
    (c) =>
      c.name.toLowerCase().includes(q) ||
      c.code.toLowerCase().includes(q) ||
      c.capital.toLowerCase().includes(q) ||
      c.region.toLowerCase().includes(q)
  );
}

export function getCountriesByRegion(
  region: 'América' | 'Europa' | 'Asia' | 'África' | 'Oceanía'
): CountryProfile[] {
  return COUNTRIES_195.filter((c) => c.region === region);
}

export function getDefaultCountry(): CountryProfile {
  // Default to Chile, Mexico, or Japan (standard benchmark seismological countries)
  return COUNTRIES_195.find((c) => c.code === 'CL') || COUNTRIES_195[0];
}
